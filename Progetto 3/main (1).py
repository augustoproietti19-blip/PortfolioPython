def calcolaBollette(datiTelefonate): #calcolo spesa in base ai minuti effettuati

    bollette = {}

    for telefonata in datiTelefonate:

        chiamante = telefonata[0]
        durata = telefonata[4]

        if chiamante not in bollette:
            bollette[chiamante] = 0

        bollette[chiamante] += durata

    for cliente in bollette:

        minuti = bollette[cliente]

        if minuti <= 20:
            bollette[cliente] = 0
        else:
            bollette[cliente] = (minuti - 20) * 0.10

    return bollette


def calcolaCelleCongestionate(datiTelefonate): # celle con numero chiamate > della media

    celle = {}

    for telefonata in datiTelefonate:

        cella = telefonata[2]

        if cella not in celle:
            celle[cella] = 0

        celle[cella] += 1

    media = sum(celle.values()) / len(celle)

    celle_congestionate = []

    for cella in celle:

        if celle[cella] > media:
            celle_congestionate.append(cella)

    return celle_congestionate


