# Dizionario della biblioteca
biblioteca = {}

# Funzioni

def aggiungi_libro(titolo, copie): #Aggiunge un nuovo libro alla biblioteca con il numero di copie

    if titolo in biblioteca:
        biblioteca[titolo] += copie
    else:
        biblioteca[titolo] = copie


def rimuovi_libro(titolo): #Rimuove un libro dalla biblioteca con la funzione del
    if titolo in biblioteca:
        del biblioteca[titolo]
    else:
        print("Errore: libro non presente.")


def verifica_disponibilita(titolo): #verifico la disponibilità del libro
    if titolo in biblioteca and biblioteca[titolo] > 0:
        return True
    else:
        return False


def prendi_in_prestito(titolo): #prendo in prestito e decremento numero di copie
    if titolo in biblioteca and biblioteca[titolo] > 0:
        biblioteca[titolo] -= 1
        print("Prestito effettuato.")
    else:
        print("Errore: libro non disponibile.")


def statistiche_biblioteca(): #libri che ho nella biblioteca e copie
    totale_libri = len(biblioteca)
    copie_totali = sum(biblioteca.values())

    if totale_libri > 0:
        media_copie = copie_totali / totale_libri #media delle copie
    else:
        media_copie = 0

    return {
        "totale_libri": totale_libri,
        "copie_totali": copie_totali,
        "media_copie": media_copie
    }


def visualizza_libri():
    if len(biblioteca) == 0:
        print("Non ci sono libri nella biblioteca.")
    else:
        for titolo, copie in biblioteca.items():
            print(titolo, "-", copie, "copie")


def restaurare_libro(titolo, copie):
    if titolo in biblioteca:
        biblioteca[titolo] += copie
    else:
        print("Errore: libro non presente.")


# Utilizzo il while

while True:

    comando = input(
        "\nComando (aggiungi, rimuovi, verifica, prestito, statistiche, visualizza, restaura, esci): "
    )

    if comando == "aggiungi":
        titolo = input("Titolo: ")
        copie = int(input("Copie: "))
        aggiungi_libro(titolo, copie)

    elif comando == "rimuovi":
        titolo = input("Titolo: ")
        rimuovi_libro(titolo)

    elif comando == "verifica":
        titolo = input("Titolo: ")
        print(verifica_disponibilita(titolo))

    elif comando == "prestito":
        titolo = input("Titolo: ")
        prendi_in_prestito(titolo)

    elif comando == "statistiche":
        print(statistiche_biblioteca())

    elif comando == "visualizza":
        visualizza_libri()

    elif comando == "restaura":
        titolo = input("Titolo: ")
        copie = int(input("Copie da aggiungere: "))
        restaurare_libro(titolo, copie)

    elif comando == "esci":
        print("Programma terminato.")
        break

    else:
        print("Comando non valido.")
